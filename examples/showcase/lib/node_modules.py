"""Find files of npm packages the browser UI uses (the showcase's node_modules)."""

from __future__ import annotations

from pathlib import Path


def resolve_package_file(start: Path, file: str) -> str:
    """``node_modules/<file>`` in ``start`` or the nearest parent that has it, like Node's resolution."""
    for directory in (start, *start.parents):
        candidate = directory / "node_modules" / file
        if candidate.is_file():
            return str(candidate)
    raise FileNotFoundError(
        f"Cannot find node_modules/{file}. Install the browser dependencies first: run `npm ci` in examples/showcase."
    )
